_STATUSISH_FREE_RE = re.compile(
    r"(?ix)\b(?P<tok>"
    + "|".join(sorted(_STATUS_VALUE_ALLOW, key=len, reverse=True))
    + r")\b"
)

# DockA / Zone12 / AB12, plus all-caps acronyms (HMAC, QEDX). Acronyms are
# dim values; without them a Phase-N plan looks fully covered while a second
# all-caps target is ignored. 3–8 letters so 2-letter function words stay out.
_CODE_TOKEN_RE = re.compile(
    r"\b(?P<tok>"
    r"[A-Z][a-z]{1,8}[A-Z][a-z]{0,3}[0-9]{0,4}"
    r"|[A-Za-z]{1,6}[0-9]+[A-Za-z0-9]{0,4}"
    r"|[A-Z]{2,6}[0-9]+"
    r"|[A-Z]{3,8}"
    r")\b"
)

